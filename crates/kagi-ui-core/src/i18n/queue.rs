//! Operation-queue strip and toast words (#355 stage 3, ADR-0204 決定 2).
//! Labels only: no explanatory sentences (user policy). Operation names
//! (`checkout`) stay English in both languages, as in the busy labels.
use super::{lang, Lang};

/// One fixed word of the queue strip.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum QueueText {
    /// Prefix of the toast for an accepted intent.
    Queued,
    /// Label above the frozen subject and body in a queued commit confirmation.
    FrozenMessage,
    /// Why a queued commit asks again instead of running without a prompt.
    DraftChanged,
    StagedChanged,
    PlanBlockers,
    PlanWarnings,
    /// `queued: N` — intents whose write has not started (決定 2).
    Count,
    Running,
    Planning,
    Confirming,
    Starting,
    WaitWrite,
    WaitPlan,
    WaitConfirm,
    WaitReconcile,
    WaitTyping,
    /// The cancel list heading.
    Cancelled,
    CancelAll,
    Clear,
    Remove,
    Full,
    ReasonRemoved,
    ReasonRejected,
    ReasonPlanError,
    ReasonChain,
    ReasonOwnerGone,
    ReasonIdentity,
    ReasonStale,
    ReasonMergeStarted,
}

pub fn queue_text(key: QueueText) -> &'static str {
    use QueueText::*;
    match (lang(), key) {
        (Lang::En, Queued) => "Queued",
        (Lang::Ja, Queued) => "キューに追加",
        (Lang::En, FrozenMessage) => "Queued message",
        (Lang::Ja, FrozenMessage) => "キューに追加したメッセージ",
        (Lang::En, DraftChanged) => "Draft changed",
        (Lang::Ja, DraftChanged) => "下書きの変更",
        (Lang::En, StagedChanged) => "Staged files changed",
        (Lang::Ja, StagedChanged) => "stage 済みの変更",
        (Lang::En, PlanBlockers) => "Can't run",
        (Lang::Ja, PlanBlockers) => "実行できない理由",
        (Lang::En, PlanWarnings) => "Warnings",
        (Lang::Ja, PlanWarnings) => "注意",
        (Lang::En, Count) => "queued",
        (Lang::Ja, Count) => "待ち",
        (Lang::En, Running) => "running",
        (Lang::Ja, Running) => "実行中",
        (Lang::En, Planning) => "preparing",
        (Lang::Ja, Planning) => "準備中",
        (Lang::En, Confirming) => "confirming",
        (Lang::Ja, Confirming) => "確認中",
        (Lang::En, Starting) => "starting",
        (Lang::Ja, Starting) => "開始中",
        (Lang::En, WaitWrite) => "waiting for another operation",
        (Lang::Ja, WaitWrite) => "他の操作待ち",
        (Lang::En, WaitPlan) => "preparing",
        (Lang::Ja, WaitPlan) => "準備中",
        (Lang::En, WaitConfirm) => "waiting: confirm",
        (Lang::Ja, WaitConfirm) => "待機: 確認",
        (Lang::En, WaitReconcile) => "waiting for a check",
        (Lang::Ja, WaitReconcile) => "確認待ち",
        (Lang::En, WaitTyping) => "waiting: typing",
        (Lang::Ja, WaitTyping) => "待機: 入力中",
        (Lang::En, Cancelled) => "cancelled",
        (Lang::Ja, Cancelled) => "取り消し",
        (Lang::En, CancelAll) => "Cancel all",
        (Lang::Ja, CancelAll) => "すべて取り消す",
        (Lang::En, Clear) => "Clear",
        (Lang::Ja, Clear) => "消去",
        (Lang::En, Remove) => "Remove",
        (Lang::Ja, Remove) => "外す",
        (Lang::En, Full) => "Queue full",
        (Lang::Ja, Full) => "キューが満杯",
        (Lang::En, ReasonRemoved) => "removed",
        (Lang::Ja, ReasonRemoved) => "外した",
        (Lang::En, ReasonRejected) => "declined",
        (Lang::Ja, ReasonRejected) => "確認で中止",
        (Lang::En, ReasonPlanError) => "couldn't prepare",
        (Lang::Ja, ReasonPlanError) => "準備できず",
        (Lang::En, ReasonChain) => "previous step failed",
        (Lang::Ja, ReasonChain) => "前の操作が不成功",
        (Lang::En, ReasonOwnerGone) => "tab closed",
        (Lang::Ja, ReasonOwnerGone) => "tab を閉じた",
        (Lang::En, ReasonIdentity) => "worktree changed",
        (Lang::Ja, ReasonIdentity) => "worktree が変わった",
        (Lang::En, ReasonStale) => "out of date",
        (Lang::Ja, ReasonStale) => "古くなった",
        (Lang::En, ReasonMergeStarted) => "merge started",
        (Lang::Ja, ReasonMergeStarted) => "merge 開始",
    }
}
