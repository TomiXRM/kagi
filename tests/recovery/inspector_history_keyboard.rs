//! #1375 / #1376: keyboard entry and return without a pointer or Git writes.
use crate::keyboard_nav::keys;
use crate::macos::{git, mount, repo_fingerprint, unmount};
use gpui::{AnyWindowHandle, Entity, VisualTestAppContext};
use kagi::ui::{i18n, list_a11y, theme, KagiApp};
use kagi_ui_file_history::FileHistoryView;

fn fixture(commits: usize) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    git(dir.path(), &["init", "-q", "-b", "main"]);
    for (path, content) in [
        ("a/file.txt", "a\n"),
        ("b/file.txt", "b\n"),
        (
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 4\n",
        ),
    ] {
        std::fs::create_dir_all(dir.path().join(path).parent().unwrap()).unwrap();
        std::fs::write(dir.path().join(path), content).unwrap();
    }
    git(dir.path(), &["add", "."]);
    git(dir.path(), &["commit", "-qm", "Initial files"]);
    for n in 0..commits {
        if n == 250 {
            git(dir.path(), &["mv", "a/file.txt", "a/previous.txt"]);
        }
        if n == 251 {
            git(dir.path(), &["mv", "a/previous.txt", "a/file.txt"]);
        }
        let path = if n == 250 {
            "a/previous.txt"
        } else {
            "a/file.txt"
        };
        std::fs::write(dir.path().join(path), format!("a {n}\n")).unwrap();
        git(dir.path(), &["add", "."]);
        git(dir.path(), &["commit", "-qm", "Change file"]);
    }
    dir
}
fn draw(cx: &mut VisualTestAppContext, window: AnyWindowHandle) {
    cx.run_until_parked();
    for _ in 0..3 {
        cx.update_window(window, |_, w, cx| {
            w.refresh();
            w.draw(cx).clear();
        })
        .unwrap();
    }
}
fn focused(
    cx: &mut VisualTestAppContext,
    app: &Entity<KagiApp>,
    window: AnyWindowHandle,
) -> Option<String> {
    cx.update_window(window, |_, w, cx| {
        app.read(cx)
            .list_row_focused_for_e2e("inspector-files-scroll", w)
    })
    .unwrap()
}
pub fn inspector(cx: &mut VisualTestAppContext) {
    let _restore = crate::surface_scrollbars::PresentationRestore::capture(cx);
    let fixture = fixture(12);
    let before = repo_fingerprint(fixture.path());
    for lang in [i18n::Lang::En, i18n::Lang::Ja] {
        i18n::set_lang(lang);
        for tree in [false, true] {
            for zoom in [1., 1.67] {
                theme::set_zoom(zoom);
                inspector_case(cx, &fixture, tree);
            }
        }
    }
    assert_eq!(before, repo_fingerprint(fixture.path()));
    for (count, generated) in [(0, false), (1, false), (200, false), (1, true)] {
        sparse_inspector(cx, count, generated);
    }
}

fn inspector_case(cx: &mut VisualTestAppContext, fixture: &tempfile::TempDir, tree: bool) {
    let (app, window) = mount(cx, fixture.path());
    app.update(cx, |app, cx| {
        app.inspector_tree_view = tree;
        let last = app.view().rows.len() - 1;
        app.select(last);
        cx.notify();
    });
    draw(cx, window);
    assert!(cx.read(|cx| app.read(cx).ui().main_diff.is_none()));
    assert!(
        !list_a11y::recorded_list("inspector-files-scroll")
            .unwrap()
            .rows
            .is_empty(),
        "Inspector has laid-out file options"
    );
    for _ in 0..80 {
        keys(cx, window, "tab");
        draw(cx, window);
        if focused(cx, &app, window).is_some() {
            break;
        }
    }
    assert!(
        focused(cx, &app, window).is_some(),
        "Inspector files must be keyboard-enterable before any diff is shown"
    );
    keys(cx, window, "home down");
    draw(cx, window);
    assert_eq!(focused(cx, &app, window).as_deref(), Some("b/file.txt"));
    let ax = list_a11y::recorded_list("inspector-files-scroll").unwrap();
    assert!(ax
        .rows
        .values()
        .any(|(name, _)| name.ends_with("a/file.txt")));
    assert!(ax
        .rows
        .values()
        .any(|(name, _)| name.ends_with("b/file.txt")));
    assert!(ax.rows.values().any(|(name, _)| name
        == &format!(
            "{} b/file.txt",
            kagi_ui_core::tree_a11y::file_status(
                Some(&kagi_domain::status::ChangeKind::Added),
                false
            )
        )));
    keys(cx, window, "enter");
    draw(cx, window);
    assert!(cx.read(|cx| app.read(cx).ui().main_diff.is_some()));
    let selected = cx.read(|cx| app.read(cx).ui().selected);
    assert_eq!(
        selected,
        cx.read(|cx| Some(app.read(cx).view().rows.len() - 1)),
        "diff activation keeps graph selection"
    );
    keys(cx, window, "end right");
    draw(cx, window);
    keys(cx, window, "end");
    draw(cx, window);
    assert_eq!(focused(cx, &app, window).as_deref(), Some("Cargo.lock"));
    keys(cx, window, "space");
    draw(cx, window);
    let ax = list_a11y::recorded_list("inspector-files-scroll").unwrap();
    assert_eq!(
        ax.rows.values().filter(|(_, selected)| *selected).count(),
        1
    );
    unmount(cx, app, window);
}
pub fn history(cx: &mut VisualTestAppContext) {
    let _restore = crate::surface_scrollbars::PresentationRestore::capture(cx);
    let fixture = fixture(499);
    std::fs::write(
        fixture.path().join("a/file.txt"),
        "uncommitted history edit\n",
    )
    .unwrap();
    let before = repo_fingerprint(fixture.path());
    for lang in [i18n::Lang::En, i18n::Lang::Ja] {
        i18n::set_lang(lang);
        for zoom in [1., 1.67] {
            theme::set_zoom(zoom);
            let (app, window) = mount(cx, fixture.path());
            app.update(cx, |app, cx| {
                app.open_file_history("a/file.txt".into(), None, cx)
            });
            draw(cx, window);
            let pane = cx.read(|cx| app.read(cx).ui().file_history.clone().unwrap());
            history_navigation(cx, &app, &pane, window);
            history_header_actions(cx, &pane, window);
            drop(pane);
            unmount(cx, app, window);
        }
    }
    assert_eq!(before, repo_fingerprint(fixture.path()));
}

fn history_navigation(
    cx: &mut VisualTestAppContext,
    app: &Entity<KagiApp>,
    pane: &Entity<FileHistoryView>,
    window: AnyWindowHandle,
) {
    // Tab starts at the host root and enters the first header button.
    cx.update_window(window, |_, w, cx| {
        let focus = app.read(cx).root_focus.clone().unwrap();
        w.focus(&focus, cx);
    })
    .unwrap();
    for _ in 0..80 {
        keys(cx, window, "tab");
        draw(cx, window);
        if cx
            .update_window(window, |_, w, cx| {
                pane.read(cx).header_focused_for_e2e(0, w, cx)
            })
            .unwrap()
        {
            break;
        }
    }
    assert!(
        cx.update_window(window, |_, w, cx| pane
            .read(cx)
            .header_focused_for_e2e(0, w, cx))
            .unwrap(),
        "Tab reaches Back"
    );
    keys(cx, window, "shift-tab down");
    draw(cx, window);
    assert_eq!(
        cx.read(|cx| pane.read(cx).data.selected),
        1,
        "Shift+Tab from first History header button must return to the list"
    );
    keys(cx, window, "end");
    draw(cx, window);
    let last = cx.read(|cx| pane.read(cx).data.history.as_ref().unwrap().entries.len() - 1);
    assert_eq!(cx.read(|cx| pane.read(cx).data.selected), last);
    keys(cx, window, "shift-tab");
    draw(cx, window);
    assert!(
        cx.update_window(window, |_, w, cx| pane
            .read(cx)
            .header_focused_for_e2e(4, w, cx))
            .unwrap(),
        "Shift+Tab from row reaches Follow"
    );
    keys(cx, window, "tab up");
    draw(cx, window);
    assert_eq!(
        cx.read(|cx| pane.read(cx).data.selected),
        last - 1,
        "Tab from last History header button must return to the remembered row"
    );
}

fn history_header_actions(
    cx: &mut VisualTestAppContext,
    pane: &Entity<FileHistoryView>,
    window: AnyWindowHandle,
) {
    let before = cx.read(|cx| pane.read(cx).data.selected);
    keys(cx, window, "tab shift-tab");
    draw(cx, window);
    assert_eq!(
        cx.read(|cx| pane.read(cx).data.selected),
        before,
        "embedded diff/header round trip retains the row"
    );
    keys(cx, window, "shift-tab shift-tab shift-tab shift-tab enter");
    draw(cx, window);
    assert!(
        cx.update_window(window, |_, w, cx| pane
            .read(cx)
            .header_focused_for_e2e(1, w, cx))
            .unwrap(),
        "Refresh retains its header focus"
    );
    keys(cx, window, "shift-tab shift-tab up");
    draw(cx, window);
    assert_eq!(
        cx.read(|cx| pane.read(cx).data.selected),
        before - 1,
        "Refresh returns to the remembered entry"
    );
    let remembered = cx.read(|cx| {
        pane.read(cx)
            .data
            .selected_entry()
            .unwrap()
            .commit
            .as_ref()
            .unwrap()
            .full_hash
            .clone()
    });
    keys(cx, window, "shift-tab enter");
    draw(cx, window);
    let (remembered_index, len) = cx.read(|cx| {
        let view = pane.read(cx);
        assert!(
            !view.data.follow_renames,
            "Follow action changes the real query"
        );
        let entries = &view.data.history.as_ref().unwrap().entries;
        (
            entries
                .iter()
                .position(|e| e.commit.as_ref().is_some_and(|c| c.full_hash == remembered))
                .unwrap_or(0),
            entries.len(),
        )
    });
    assert!(
        cx.update_window(window, |_, w, cx| pane
            .read(cx)
            .header_focused_for_e2e(4, w, cx))
            .unwrap(),
        "Follow retains its header focus"
    );
    keys(cx, window, "tab down");
    draw(cx, window);
    assert_eq!(
        cx.read(|cx| pane.read(cx).data.selected),
        (remembered_index + 1).min(len - 1),
        "Follow returns to the remembered surviving row"
    );
}

fn sparse_inspector(cx: &mut VisualTestAppContext, count: usize, generated: bool) {
    let fixture = tempfile::tempdir().unwrap();
    git(fixture.path(), &["init", "-q", "-b", "main"]);
    for ix in 0..count {
        let path = if generated {
            "Cargo.lock".into()
        } else {
            format!("file-{ix:03}.txt")
        };
        std::fs::write(fixture.path().join(path), "file contents\n").unwrap();
    }
    git(fixture.path(), &["add", "."]);
    git(
        fixture.path(),
        &["commit", "--allow-empty", "-qm", "Sparse inspector"],
    );
    let before = repo_fingerprint(fixture.path());
    let (app, window) = mount(cx, fixture.path());
    app.update(cx, |app, cx| {
        app.inspector_tree_view = false;
        app.inspector_generated_expanded = false;
        app.select(0);
        cx.notify();
    });
    draw(cx, window);
    for _ in 0..80 {
        keys(cx, window, "tab");
        draw(cx, window);
        if focused(cx, &app, window).is_some() {
            break;
        }
    }
    if count == 0 {
        assert!(focused(cx, &app, window).is_none());
        assert!(cx.read(|cx| app.read(cx).ui().main_diff.is_none()));
    } else {
        assert!(focused(cx, &app, window).is_some());
        if generated {
            keys(cx, window, "space");
            draw(cx, window);
            keys(cx, window, "down");
            draw(cx, window);
            assert_eq!(focused(cx, &app, window).as_deref(), Some("Cargo.lock"));
        } else {
            keys(cx, window, "end");
            draw(cx, window);
            assert_eq!(
                focused(cx, &app, window).as_deref(),
                Some(format!("file-{:03}.txt", count.min(100) - 1).as_str())
            );
        }
        keys(cx, window, "enter");
        draw(cx, window);
        assert!(cx.read(|cx| app.read(cx).ui().main_diff.is_some()));
    }
    unmount(cx, app, window);
    assert_eq!(before, repo_fingerprint(fixture.path()));
}
