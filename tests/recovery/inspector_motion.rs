//! #1617: frozen native Inspector selection washes and generated-row splices.
use crate::macos::{git, mount, repo_fingerprint, unmount};
use gpui::{point, px, AnyWindowHandle, Bounds, Entity, Pixels, VisualTestAppContext};
use kagi::ui::{e2e, list_a11y, theme, KagiApp};
use kagi_ui_core::motion;
use std::time::{Duration, Instant};

struct MotionRestore(bool);
impl Drop for MotionRestore {
    fn drop(&mut self) {
        motion::set_clock_for_e2e(None);
        theme::set_reduce_motion(self.0);
    }
}
fn fixture() -> tempfile::TempDir {
    let repo = tempfile::tempdir().unwrap();
    git(repo.path(), &["init", "-q", "-b", "main"]);
    for (path, text) in [
        ("a.txt", "first\nsecond\n"),
        ("b.txt", "first\nsecond\n"),
        (
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 4\n",
        ),
        ("package-lock.json", "{\"lockfileVersion\": 3}\n"),
    ] {
        std::fs::write(repo.path().join(path), text).unwrap();
    }
    git(repo.path(), &["add", "."]);
    git(repo.path(), &["commit", "-qm", "Inspector motion files"]);
    repo
}
fn draw(cx: &mut VisualTestAppContext, window: AnyWindowHandle) {
    cx.run_until_parked();
    for _ in 0..3 {
        // The recorder intentionally retains offscreen rows across frames.
        // This oracle needs only the semantic rows emitted in this frame.
        list_a11y::clear_recorded_lists();
        cx.update_window(window, |_, window, cx| {
            window.refresh();
            window.draw(cx).clear();
        })
        .unwrap();
    }
}
fn frame(cx: &mut VisualTestAppContext, window: AnyWindowHandle, at: Instant) {
    motion::set_clock_for_e2e(Some(at));
    draw(cx, window);
}
fn bounds(window: AnyWindowHandle, id: &str) -> Bounds<Pixels> {
    e2e::control_bounds(window.window_id(), id).unwrap_or_else(|| panic!("missing {id}"))
}
fn paint(window: AnyWindowHandle, index: usize) -> Bounds<Pixels> {
    bounds(window, &format!("inspector-file-paint-{index}"))
}
fn fill(cx: &mut VisualTestAppContext, window: AnyWindowHandle, index: usize) -> [u8; 4] {
    let row = paint(window, index);
    cx.update_window(window, |_, window, _| {
        let image = window
            .render_to_image()
            .expect("native Inspector wash pixels");
        let scale = window.scale_factor();
        image
            .get_pixel(
                (f32::from(row.right() - px(4.)) * scale) as u32,
                (f32::from(row.top() + px(1.)) * scale) as u32,
            )
            .0
    })
    .unwrap()
}
fn distance(a: [u8; 4], b: [u8; 4]) -> u32 {
    (0..3).map(|i| a[i].abs_diff(b[i]) as u32).sum()
}
// Clear each paint observation before drawing: an old label sample must never
// satisfy an intermediate-frame assertion if virtualized content stops painting.
fn inks(cx: &mut VisualTestAppContext, window: AnyWindowHandle, index: usize) -> [gpui::Hsla; 3] {
    let ids = [
        format!("inspector-file-name-{index}"),
        format!("inspector-file-badge-{index}"),
        format!("diffstat-additions-{index}"),
    ];
    for id in &ids {
        e2e::clear_control_bounds(window.window_id(), id);
    }
    draw(cx, window);
    ids.map(|id| {
        e2e::control_paint(window.window_id(), &id)
            .unwrap_or_else(|| panic!("missing fresh {id} paint"))
            .text_color
    })
}
fn assert_inks(actual: [gpui::Hsla; 3], wash: f32, active: bool) {
    let palette = theme::theme();
    let normal = [
        palette.text_main,
        palette.change_added,
        palette.change_added,
    ];
    for (index, (actual, normal)) in actual.into_iter().zip(normal).enumerate() {
        let normal = gpui::Hsla::from(gpui::rgb(normal)).to_rgb();
        let selected = if index == 2 {
            palette.selection_secondary_foreground(true)
        } else {
            palette.selection_foreground(true)
        }
        .to_rgb();
        let wash = if active { wash } else { 0. };
        let expected = [
            normal.r + (selected.r - normal.r) * wash,
            normal.g + (selected.g - normal.g) * wash,
            normal.b + (selected.b - normal.b) * wash,
            normal.a + (selected.a - normal.a) * wash,
        ];
        let actual = actual.to_rgb();
        for (actual, expected) in [actual.r, actual.g, actual.b, actual.a]
            .into_iter()
            .zip(expected)
        {
            assert!(
                (actual - expected).abs() < 0.002,
                "foreground {index}, wash={wash}: {actual} != {expected}"
            );
        }
    }
}
fn click(cx: &mut VisualTestAppContext, window: AnyWindowHandle, id: &str) {
    let row = bounds(window, id);
    cx.simulate_click(
        window,
        point(row.right() - px(7.), row.center().y),
        gpui::Modifiers::none(),
    );
    // Do not leave hover on the row whose wash is sampled.
    cx.simulate_mouse_move(window, point(px(1.), px(1.)), None, gpui::Modifiers::none());
}
fn selected(path: &str) {
    let ax = list_a11y::recorded_list("inspector-files-scroll").unwrap();
    let rows: Vec<_> = ax.rows.values().filter(|(_, selected)| *selected).collect();
    assert_eq!(rows.len(), 1, "selection intent/AX must not wait for paint");
    assert!(rows[0].0.ends_with(path));
}
fn generated_semantics(present: bool) {
    let ax = list_a11y::recorded_list("inspector-files-scroll").unwrap();
    for path in ["Cargo.lock", "package-lock.json"] {
        assert_eq!(
            ax.rows.values().any(|(name, _)| name.ends_with(path)),
            present,
            "closing ghosts are absent from the semantic list immediately"
        );
    }
}
fn index(cx: &mut VisualTestAppContext, app: &Entity<KagiApp>, path: &str) -> usize {
    cx.read(|cx| app.read(cx).inspector_file_index_for_e2e(path))
        .unwrap()
}
fn near(a: Pixels, b: Pixels, reason: &str) {
    assert!((a - b).abs() <= px(1.), "{reason}: {a:?} != {b:?}");
}
fn case(cx: &mut VisualTestAppContext, repo: &std::path::Path, tree: bool) {
    motion::set_clock_for_e2e(None);
    theme::set_reduce_motion(false);
    let (app, window) = mount(cx, repo);
    app.update(cx, |app, cx| {
        app.inspector_visible = true;
        app.inspector_tree_view = tree;
        app.inspector_generated_expanded = false;
        app.sidebar.width = 240.;
        app.panel_width = 360.;
        app.bottom_panel_open = false;
        app.select(0);
        app.set_window_active_for_e2e(true, cx);
        app.close_main_diff();
        cx.notify();
    });
    draw(cx, window);
    let a = index(cx, &app, "a.txt");
    let b = index(cx, &app, "b.txt");
    let first = index(cx, &app, "Cargo.lock");
    let second = index(cx, &app, "package-lock.json");
    let t = Instant::now();
    frame(cx, window, t);
    let empty = fill(cx, window, a);
    assert_inks(inks(cx, window, a), 0., true);
    click(cx, window, &format!("inspector-file-{a}"));
    frame(cx, window, t);
    selected("a.txt");
    assert!(
        distance(fill(cx, window, a), empty) <= 3,
        "wash starts continuously"
    );
    assert_inks(inks(cx, window, a), 0., true);
    frame(cx, window, t + Duration::from_millis(60));
    let mid = fill(cx, window, a);
    // 60ms of the shared 180ms OutCubic wash is 1 - (2/3)^3.
    assert_inks(inks(cx, window, a), 19. / 27., true);
    frame(cx, window, t + Duration::from_millis(300));
    let full = fill(cx, window, a);
    assert_inks(inks(cx, window, a), 1., true);
    assert!(
        distance(mid, empty) > 3 && distance(mid, full) > 3,
        "native pixels must show a genuine intermediate selection opacity"
    );
    click(cx, window, &format!("inspector-file-{b}"));
    frame(cx, window, t + Duration::from_millis(300));
    selected("b.txt");
    assert_inks(inks(cx, window, a), 1., true);
    frame(cx, window, t + Duration::from_millis(360));
    let turning = fill(cx, window, a);
    let turning_inks = inks(cx, window, a);
    assert_inks(turning_inks, 8. / 27., true);
    click(cx, window, &format!("inspector-file-{a}"));
    frame(cx, window, t + Duration::from_millis(360));
    selected("a.txt");
    assert!(
        distance(turning, fill(cx, window, a)) <= 3,
        "selection reversal has no jump"
    );
    assert_eq!(
        inks(cx, window, a),
        turning_inks,
        "foreground reverses from its current paint, not semantic selection"
    );
    frame(cx, window, t + Duration::from_millis(660));
    assert!(
        distance(full, fill(cx, window, a)) <= 3,
        "selection settles exactly"
    );
    assert_inks(inks(cx, window, a), 1., true);
    assert_inks(inks(cx, window, b), 0., true);
    app.update(cx, |app, cx| app.set_window_active_for_e2e(false, cx));
    assert_inks(inks(cx, window, a), 1., false);
    selected("a.txt");
    app.update(cx, |app, cx| app.set_window_active_for_e2e(true, cx));
    assert_inks(inks(cx, window, a), 1., true);

    frame(cx, window, t + Duration::from_millis(700));
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(700));
    generated_semantics(true);
    let start = paint(window, second).top();
    frame(cx, window, t + Duration::from_millis(760));
    let opening = paint(window, second).top();
    frame(cx, window, t + Duration::from_millis(1000));
    let settled = paint(window, second).top();
    let height = KagiApp::inspector_row_height_for_e2e();
    near(
        settled - start,
        height,
        "second generated row unfolds by one preceding slot",
    );
    assert!(
        opening > start && opening < settled,
        "real rendered row is mid-splice"
    );
    near(
        settled - paint(window, first).top(),
        height,
        "settled uniform row slots",
    );

    frame(cx, window, t + Duration::from_millis(1100));
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(1100));
    generated_semantics(false);
    near(
        paint(window, second).top(),
        settled,
        "retained closing content starts without a jump",
    );
    frame(cx, window, t + Duration::from_millis(1160));
    let closing = paint(window, second).top();
    assert!(
        closing < settled && closing > settled - height,
        "closing ghost moves continuously"
    );
    // Clicking retained paint must not open a diff or publish semantic selection.
    let ghost = bounds(window, &format!("inspector-file-ghost-{second}"));
    cx.simulate_click(window, ghost.center(), gpui::Modifiers::none());
    draw(cx, window);
    selected("a.txt");
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(1160));
    generated_semantics(true);
    near(
        paint(window, second).top(),
        closing,
        "reopening reverses retained rows in place",
    );
    frame(cx, window, t + Duration::from_millis(1460));
    near(
        paint(window, second).top(),
        settled,
        "reopened rows settle at their original slots",
    );

    frame(cx, window, t + Duration::from_millis(1500));
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(1500));
    e2e::clear_control_bounds(
        window.window_id(),
        &format!("inspector-file-ghost-{second}"),
    );
    frame(cx, window, t + Duration::from_millis(1800));
    generated_semantics(false);
    assert!(
        e2e::control_bounds(
            window.window_id(),
            &format!("inspector-file-ghost-{second}")
        )
        .is_none(),
        "ordinary closing drops retained content when settled"
    );
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(1800));
    frame(cx, window, t + Duration::from_millis(2100));
    near(
        paint(window, second).top(),
        settled,
        "ordinary opening settles again",
    );
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(2100));
    frame(cx, window, t + Duration::from_millis(2160));
    theme::set_reduce_motion(true);
    e2e::clear_control_bounds(
        window.window_id(),
        &format!("inspector-file-ghost-{second}"),
    );
    frame(cx, window, t + Duration::from_millis(2160));
    generated_semantics(false);
    assert!(
        e2e::control_bounds(
            window.window_id(),
            &format!("inspector-file-ghost-{second}")
        )
        .is_none(),
        "enabling Reduce Motion retires closing paint immediately"
    );
    click(cx, window, "generated-fold-header");
    frame(cx, window, t + Duration::from_millis(2160));
    generated_semantics(true);
    near(
        paint(window, second).top(),
        settled,
        "reduced opening is immediate",
    );
    click(cx, window, &format!("inspector-file-{b}"));
    frame(cx, window, t + Duration::from_millis(2160));
    selected("b.txt");
    assert!(
        distance(fill(cx, window, b), full) <= 3,
        "reduced selection paints its endpoint immediately"
    );
    assert_inks(inks(cx, window, b), 1., true);
    theme::set_reduce_motion(false);
    frame(cx, window, t + Duration::from_millis(2200));
    assert!(
        distance(fill(cx, window, b), full) <= 3,
        "disabling reduction cannot resurrect motion"
    );
    motion::set_clock_for_e2e(None);
    unmount(cx, app, window);
}

pub fn scenario(cx: &mut VisualTestAppContext) {
    let _presentation = crate::surface_scrollbars::PresentationRestore::capture(cx);
    let _keys = crate::gui_isolation::SavedKeys::keep(&["reduce_motion"]);
    let _motion = MotionRestore(theme::reduce_motion());
    let repo = fixture();
    let before = repo_fingerprint(repo.path());
    for preset in ["apple-light", "apple-dark"] {
        assert!(theme::set_active(preset));
        for tree in [false, true] {
            for zoom in [1., 1.67] {
                theme::set_zoom(zoom);
                cx.update(theme::sync_gpui_component_theme);
                case(cx, repo.path(), tree);
            }
        }
    }
    assert_eq!(
        before,
        repo_fingerprint(repo.path()),
        "motion never writes Git state"
    );
    eprintln!("[gui-e2e] PASS inspector_file_motion");
}
